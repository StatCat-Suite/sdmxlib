#: Referenceable in SDMX-JSON only where an *enumeration* is (#422). SDMX-JSON
#: 2.0's generic ``urn`` pattern spells the class ``Valuelist`` — a typo 2.1
#: corrects — so `PAIRS_JSON`, read as the two versions' intersection, leaves it
#: out. But both versions type a representation's ``enumeration`` and a
#: representation map's ends as ``AnyCodelistReferenceType``, whose own pattern
#: is ``codelist\.((Codelist)|(ValueList))``, so a reference there validates in
#: both. Elsewhere it does not, and is refused as any unknown class is.
ENUMERATION_PAIR_JSON: tuple[str, str] = ("codelist", "ValueList")
