"""Which classes each target format can reference (#430).

A reference is written as its URN's package and class, unchecked, so one
naming a class the target does not define — a registry's proprietary
`PublicationTable` — was written schema-invalid in every format.
`validation._check_ref_classes` refuses it instead.

Read out of the vendored schemas and kept equal to them by
`tests/unit/test_ref_classes.py`; edit by regenerating, not by hand:

- SDMX-ML 2.1: ``ObjectTypeCodelistType`` (``Ref@class``) and
  ``PackageTypeCodelistType`` (``Ref@package``), checked separately as the
  schema checks them.
- SDMX-ML 3.0 / 3.1: ``UrnClassesPart``, one ``package.Class`` per pattern.
- SDMX-JSON: the ``urn`` pattern, as allowed by both 2.0 and 2.1 — the
  writer's output is validated against either.
"""

