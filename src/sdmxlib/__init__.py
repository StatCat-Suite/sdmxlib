def len[R: RowKind]() -> Agg[R]:  # noqa: A001 - polars' `pl.len()`; nothing in this module calls the builtin
    """The number of rows, as an aggregate — `count(*)`, named for polars' `pl.len()`.

    For `Query.agg`, which folds a whole query into one row, so the row count
    can come out of the same scan as the other aggregates (#414):

        obs.agg(SEX=obs.col("SEX").unique(), n=sl.len())

    A function rather than a column method because it counts *rows*, not the
    values of any column — the same reason `group_by(...).len()` is a method on
    the grouping rather than on a column. The row kind is taken from where it is
    used, so it fits any query's `agg`.

    Shadows the builtin only as `sl.len`; this module never calls `len()`
    itself, which is why it is defined here rather than re-exported from a
    module that would need a second suppression.
    """
    return Agg[R]("count", ())


